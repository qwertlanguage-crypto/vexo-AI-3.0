import { Conversation, UserSettings } from '../types';

export function exportConversationToMarkdown(conv: Conversation): void {
  let md = `# ${conv.title}\n\n`;
  md += `*Generated by Vexo-AI on ${new Date(conv.createdAt).toLocaleString()}*\n`;
  md += `*Model: ${conv.model}*\n\n---\n\n`;

  for (const msg of conv.messages) {
    const roleName = msg.role === 'user' ? 'You' : 'Vexo-AI';
    md += `### ${roleName} (${new Date(msg.timestamp).toLocaleTimeString()})\n\n`;

    if (msg.image) {
      md += `*[Attached Image: ${msg.image.mimeType}]*\n\n`;
    }

    if (msg.content) {
      md += `${msg.content}\n\n`;
    }

    if (msg.generatedImage) {
      md += `**[Generated Artwork: "${msg.generatedImage.prompt}"]**\n\n`;
    }

    if (msg.sources && msg.sources.length > 0) {
      md += `**Sources Referenced:**\n`;
      for (const s of msg.sources) {
        md += `- [${s.title}](${s.url})\n`;
      }
      md += `\n`;
    }

    md += `---\n\n`;
  }

  downloadFile(`${slugify(conv.title)}-vexo-chat.md`, md, 'text/markdown');
}

export function exportConversationToText(conv: Conversation): void {
  let txt = `Vexo-AI Conversation: ${conv.title}\n`;
  txt += `Date: ${new Date(conv.createdAt).toLocaleString()}\n`;
  txt += `==============================================\n\n`;

  for (const msg of conv.messages) {
    const roleName = msg.role === 'user' ? 'USER' : 'VEXO-AI';
    txt += `[${roleName}] - ${new Date(msg.timestamp).toLocaleTimeString()}\n`;
    txt += `${msg.content}\n\n`;
  }

  downloadFile(`${slugify(conv.title)}-vexo-chat.txt`, txt, 'text/plain');
}

export function exportFullBackup(conversations: Conversation[], settings: UserSettings): void {
  const data = {
    app: 'vexo-ai',
    version: '4.9',
    exportedAt: new Date().toISOString(),
    conversations,
    settings,
  };
  const jsonStr = JSON.stringify(data, null, 2);
  downloadFile(`vexo-ai-backup-${new Date().toISOString().slice(0, 10)}.json`, jsonStr, 'application/json');
}

function downloadFile(filename: string, content: string, contentType: string) {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/[\s_-]+/g, '-')
    .substring(0, 40) || 'chat';
}
